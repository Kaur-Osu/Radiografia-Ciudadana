import { test, expect } from '@playwright/test';

test('routes, themes, comparison, charts and territory selection', async ({ page }) => {
  const errors: string[]=[];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  await expect(page.getByRole('heading', { name: 'Panel General' })).toBeVisible();
  await expect(page.locator('.recharts-line')).toHaveCount(1);
  await expect(page.locator('.leaflet-interactive')).toHaveCount(32);
  await expect(page.locator('select')).toHaveValue('3');
  await page.screenshot({ path: 'test-results/home-light.png', fullPage: true });
  await page.getByRole('button', { name: 'Alternar tema claro/oscuro' }).click();
  await expect(page.locator('html')).toHaveClass('dark');
  await expect(page.locator('main')).toHaveCSS('color','rgb(243, 237, 242)');
  await expect(page.locator('nav')).toHaveCSS('background-color','rgb(36, 31, 39)');
  await page.screenshot({ path: 'test-results/home-dark.png', fullPage: true });
  await page.reload();
  await expect(page.locator('html')).toHaveClass('dark');
  await page.goto('/comparador');
  await page.locator('select').nth(0).selectOption('1');
  await page.locator('select').nth(1).selectOption('3');
  await page.getByRole('button', { name:'Comparar', exact:true }).click();
  await expect(page.getByText('Comparación: 2018 vs 2024')).toBeVisible();
  await expect(page.locator('.recharts-bar-rectangle')).toHaveCount(2);
  await page.screenshot({ path: 'test-results/comparison-dark.png', fullPage: true });
  await page.goto('/explorador');
  await expect(page.getByRole('button', { name:'Ver ficha' })).toHaveCount(32);
  await expect(page.locator('.recharts-bar-rectangle')).toHaveCount(32);
  await page.getByRole('button', { name:'Ver ficha' }).first().click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await page.keyboard.press('Escape');
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.locator('.leaflet-interactive').first().click({force:true});
  await expect(page.getByRole('dialog')).toBeVisible();
  await page.getByRole('button',{name:'Cerrar ficha'}).click();
  await page.goto('/perfiles');
  await page.locator('select').nth(1).selectOption('1');
  await expect(page.getByText('Diagnóstico Cívico: AGUASCALIENTES')).toBeVisible();
  await expect(page.locator('.recharts-radar-polygon')).toHaveCount(1);
  await page.screenshot({path:'test-results/profile-dark.png',fullPage:true});
  await page.getByRole('button', { name:'Limpiar selección' }).click();
  await expect(page.getByText('Diagnóstico Cívico: AGUASCALIENTES')).toHaveCount(0);
  await page.goto('/metodologia');
  await expect(page.getByRole('heading',{name:'Fuentes y Metodología'})).toBeVisible();
  await page.getByRole('button', { name:'Alternar tema claro/oscuro' }).click();
  await expect(page.locator('html')).not.toHaveClass('dark');
  expect(errors).toEqual([]);
});

test('mobile navigation and chart dimensions', async ({ page }) => {
  await page.setViewportSize({width:390,height:844});
  await page.goto('/');
  await expect(page.locator('.recharts-line')).toHaveCount(1);
  await expect(page.locator('.recharts-bar-rectangle')).toHaveCount(10);
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
  await page.screenshot({ path:'test-results/mobile.png',fullPage:true });
  await page.locator('[aria-label="Navegación principal"]').getByRole('link',{name:'Comparador Histórico'}).click();
  await expect(page.getByRole('heading',{name:'Comparador Histórico'})).toBeVisible();
});
